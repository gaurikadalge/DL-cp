"""Citation validation, source resolution, and provenance verification."""

import logging
import re

from app.schemas import Citation, StableChunkMetadata

logger = logging.getLogger("rag_engine.citations")

# Pattern matching citation tags like [1], [2], [10]
CITATION_TAG_REGEX = re.compile(r"\[(\d+)\]")


def extract_citation_snippet(chunk_text: str, max_chars: int = 250) -> str:
    """Extract a clean, informative excerpt from the source chunk text for verifiable citation."""
    cleaned = " ".join(chunk_text.split())
    if len(cleaned) <= max_chars:
        return cleaned
    # Truncate at sentence or word boundary
    truncated = cleaned[:max_chars]
    last_period = truncated.rfind(".")
    if last_period > 80:
        return truncated[: last_period + 1]
    return truncated.rsplit(" ", 1)[0] + "..."


class CitationValidator:
    """Validates citations against actually retrieved evidence and resolves authoritative metadata."""

    @staticmethod
    def validate_citations(
        answer: str,
        citation_map: dict[str, StableChunkMetadata],
    ) -> tuple[list[Citation], set[str]]:
        """Extract and validate all citation markers in the generated answer.

        Args:
            answer: Text generated by the LLM containing inline tags like [1].
            citation_map: Authoritative mapping of tags (e.g. "[1]") to StableChunkMetadata.

        Returns:
            Tuple of:
            - resolved_citations: List of valid Citation models mapped to actual chunks.
            - unresolvable_tags: Set of tags found in answer that could not be resolved.
        """
        if not answer:
            return [], set()

        raw_tags = CITATION_TAG_REGEX.findall(answer)
        unique_tags = [f"[{num}]" for num in sorted(set(raw_tags), key=lambda x: int(x))]

        resolved_citations: list[Citation] = []
        unresolvable_tags: set[str] = set()

        for tag in unique_tags:
            chunk = citation_map.get(tag)
            if chunk is None:
                logger.warning("Answer references unknown citation tag '%s' not present in retrieved context.", tag)
                unresolvable_tags.add(tag)
                continue

            snippet = extract_citation_snippet(chunk.text)
            citation = Citation(
                citation_id=tag,
                chunk_id=chunk.chunk_id,
                document_id=chunk.document_id,
                source_filename=chunk.source_filename,
                page_number=chunk.page_number,
                section=chunk.section,
                snippet=snippet,
            )
            resolved_citations.append(citation)

        logger.info(
            "Resolved %d valid citations; %d unresolvable tags.",
            len(resolved_citations),
            len(unresolvable_tags),
        )
        return resolved_citations, unresolvable_tags
